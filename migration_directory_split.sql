USE sena_personal;

ALTER TABLE instructors
    DROP INDEX uq_instructors_email,
    MODIFY email VARCHAR(190) NULL,
    MODIFY specialty VARCHAR(150) NULL,
    ADD COLUMN document_number VARCHAR(50) NULL AFTER specialty,
    ADD COLUMN phone VARCHAR(40) NULL AFTER document_number,
    ADD COLUMN personal_email VARCHAR(190) NULL AFTER phone,
    ADD COLUMN affiliation_type VARCHAR(100) NULL AFTER personal_email,
    ADD COLUMN job_title VARCHAR(150) NULL AFTER affiliation_type,
    ADD COLUMN role_name VARCHAR(50) NOT NULL DEFAULT 'Instructor' AFTER job_title,
    ADD COLUMN supervisor VARCHAR(150) NULL AFTER role_name,
    ADD COLUMN site_name VARCHAR(150) NULL AFTER supervisor,
    ADD COLUMN site_address TEXT NULL AFTER site_name,
    ADD COLUMN site_id VARCHAR(50) NULL AFTER site_address,
    ADD COLUMN regional VARCHAR(100) NULL AFTER site_id,
    ADD COLUMN contract_number VARCHAR(80) NULL AFTER regional,
    ADD COLUMN contract_end_date DATE NULL AFTER contract_number,
    ADD COLUMN contract_end_date_raw VARCHAR(50) NULL AFTER contract_end_date,
    ADD COLUMN vpn_access VARCHAR(100) NULL AFTER contract_end_date_raw,
    ADD COLUMN extension_ip VARCHAR(100) NULL AFTER vpn_access,
    ADD COLUMN source_row SMALLINT UNSIGNED NULL AFTER extension_ip,
    ADD COLUMN duplicate_in_source BOOLEAN NOT NULL DEFAULT FALSE AFTER source_row,
    ADD COLUMN duplicate_with_other_category BOOLEAN NOT NULL DEFAULT FALSE AFTER duplicate_in_source,
    ADD COLUMN invalid_contract_date BOOLEAN NOT NULL DEFAULT FALSE AFTER duplicate_with_other_category,
    ADD KEY idx_instructors_email (email),
    ADD KEY idx_instructors_document (document_number),
    ADD UNIQUE KEY uq_instructors_source_row (source_row);

CREATE TABLE IF NOT EXISTS administrative_staff (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    email VARCHAR(190) NULL,
    specialty VARCHAR(150) NULL,
    document_number VARCHAR(50) NULL,
    phone VARCHAR(40) NULL,
    personal_email VARCHAR(190) NULL,
    affiliation_type VARCHAR(100) NULL,
    job_title VARCHAR(150) NULL,
    role_name VARCHAR(50) NOT NULL DEFAULT 'Administrativo',
    supervisor VARCHAR(150) NULL,
    site_name VARCHAR(150) NULL,
    site_address TEXT NULL,
    site_id VARCHAR(50) NULL,
    regional VARCHAR(100) NULL,
    contract_number VARCHAR(80) NULL,
    contract_end_date DATE NULL,
    contract_end_date_raw VARCHAR(50) NULL,
    vpn_access VARCHAR(100) NULL,
    extension_ip VARCHAR(100) NULL,
    source_row SMALLINT UNSIGNED NULL,
    duplicate_in_source BOOLEAN NOT NULL DEFAULT FALSE,
    duplicate_with_other_category BOOLEAN NOT NULL DEFAULT FALSE,
    invalid_contract_date BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_administrative_email (email),
    KEY idx_administrative_document (document_number),
    UNIQUE KEY uq_administrative_source_row (source_row)
) ENGINE=InnoDB;
